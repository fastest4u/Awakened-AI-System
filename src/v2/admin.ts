function input(argv: readonly string[]): { command: string; values: Record<string, string> } {
  const [command, ...flags] = argv;
  if (!command || !["initialize-fresh", "resume-initialization", "status"].includes(command)) throw new FreshStartError("FRESH_START_RELEASE_NOT_READY");
  const names = ["--project-root", "--v2-vault-root", "--v1-archive-root", "--release-manifest"];
  const values: Record<string, string> = {};
  for (let index = 0; index < flags.length; index += 2) {
    const name = flags[index]!, value = flags[index + 1];
    if (!names.includes(name) || Object.hasOwn(values, name) || !value || !isAbsolute(value)) throw new FreshStartError("FRESH_START_CONFIG_INVALID");
    values[name] = value;
  }
  if (Object.keys(values).length !== names.length) throw new FreshStartError("FRESH_START_CONFIG_INVALID");
  return { command, values };
}

function readReleaseManifest(path: string): string {
  const before = lstatSync(path, { bigint: true });
  if (!before.isFile() || before.isSymbolicLink() || before.nlink !== 1n || before.size > 16384n) throw new Error();
  const handle = openSync(path, "r");
  try {
    const unchanged = () => {
      for (const actual of [fstatSync(handle, { bigint: true }), lstatSync(path, { bigint: true })]) {
        if (!actual.isFile() || actual.isSymbolicLink() || actual.nlink !== 1n) throw new Error();
        for (const key of ["dev", "ino", "size", "mtimeNs", "ctimeNs"] as const)
          if (actual[key] !== before[key]) throw new Error();
      }
      if (realpathSync.native(path) !== path) throw new Error();
    };
    // Bind both the single-link requirement and identity to the actual reader,
    // before its first content read, even if the checked pathname was replaced.
    unchanged();
    const bytes = Buffer.alloc(Number(before.size) + 1);
    let used = 0;
    while (used < bytes.length) {
      const count = readSync(handle, bytes, used, bytes.length - used, null);
      if (count === 0) break;
      used += count;
    }
    unchanged();
    if (used !== Number(before.size)) throw new Error();
    return bytes.subarray(0, used).toString("utf8");
  } finally { closeSync(handle); }
}

export async function runV2Admin(argv: readonly string[]): Promise<FreshStartStatus> {
  const { command, values } = input(argv);
  const dummy = "00000000-0000-4000-8000-000000000000";
  const roots = loadV2LaunchConfig({ MEMORY_PROJECT_ROOT: values["--project-root"], MEMORY_V2_VAULT_PATH: values["--v2-vault-root"],
    MEMORY_V1_ARCHIVE_PATH: values["--v1-archive-root"], MEMORY_V2_RELEASE_ID: dummy });
  const paths = await assertFreshStartPaths(roots);
  let manifestPath: string;
  try { manifestPath = realpathSync.native(values["--release-manifest"]!); }
  catch { throw new FreshStartError("FRESH_START_INPUT_INVALID"); }
  if (freshStartPathContains(paths.v1ArchiveRoot, manifestPath)) throw new FreshStartError("FRESH_START_PATH_OVERLAP");
  let manifest: { initializationId: string; release: FreshStartInitializeInput["release"] };
  try {
    const raw = JSON.parse(readReleaseManifest(manifestPath));
    if (!raw || typeof raw !== "object" || Object.keys(raw).sort().join(",") !== "initializationId,release"
      || typeof raw.initializationId !== "string" || !/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/u.test(raw.initializationId)
      || !raw.release || typeof raw.release !== "object" || ["projectId", "vaultId", "storeId"].some(key => Object.hasOwn(raw.release, key))) throw new Error();
    // Reuse the versioned strict decoder; fresh identities are generated by initialization.
    const { projectId: _p, vaultId: _v, storeId: _s, ...release } = decodeFreshStartRelease({ ...raw.release, projectId: dummy, vaultId: dummy, storeId: dummy });
    manifest = { initializationId: raw.initializationId, release };
  } catch { throw new FreshStartError("FRESH_START_INPUT_INVALID"); }
  const explicit = loadV2LaunchConfig({ MEMORY_PROJECT_ROOT: values["--project-root"], MEMORY_V2_VAULT_PATH: values["--v2-vault-root"],
    MEMORY_V1_ARCHIVE_PATH: values["--v1-archive-root"], MEMORY_V2_RELEASE_ID: manifest.release.releaseId });
  const config = Object.freeze({ ...paths, releaseId: explicit.releaseId });
  const measured = inspectV2Build();
  assertPreparedRelease(manifest.release, config, measured);
  if (command !== "status") {
    // Paths are local-operator output only, never part of MCP diagnostics.
    process.stderr.write(`Resolved V2 destination: ${JSON.stringify(paths.v2VaultRoot)}\n`);
    const actor = userInfo();
    const actorFingerprint = createHash("sha256").update(JSON.stringify({ host: hostname(), username: actor.username, uid: actor.uid })).digest("hex");
    const initializer = new FreshStartInitializer({ inspectBuild: () => inspectV2Build(), actorFingerprint });
    const preparation = { ...paths, ...manifest };
    if (command === "initialize-fresh") await initializer.initializeFresh(preparation);
    else await initializer.resumeInitialization(preparation);
  }
  const foundation = await createV2Foundation(config);
  let status: FreshStartStatus | undefined, primary: unknown;
  try { status = await foundation.status(); } catch (error) { primary = error; }
  try { await foundation.close(); } catch (error) { primary ??= error; }
  if (primary) throw primary;
  return status!;
}
